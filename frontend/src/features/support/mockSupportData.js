// Active mutable state for DEV fallback simulation
let activeMockTickets = JSON.parse(JSON.stringify(INITIAL_MOCK_TICKETS));

export function getMockTickets() {
  return JSON.parse(JSON.stringify(activeMockTickets));
}

export function updateMockTicket(ticketId, updater) {
  const index = activeMockTickets.findIndex((t) => t.id === Number(ticketId));
  if (index === -1) return null;
  const current = activeMockTickets[index];
  const updated = typeof updater === "function" ? updater(current) : { ...current, ...updater };
  activeMockTickets[index] = updated;
  return JSON.parse(JSON.stringify(updated));
}

export function resetMockTickets() {
  activeMockTickets = JSON.parse(JSON.stringify(INITIAL_MOCK_TICKETS));
  return getMockTickets();
}
